-- 앱 공지사항 테이블
-- 어드민(웹)에서 CRUD, 앱에서는 로그인 사용자만 조회합니다.
-- 작성 즉시 공개되며 카테고리/중요도 구분은 없습니다.
create table public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.notices is '앱 공지사항';
comment on column public.notices.id is '공지 id';
comment on column public.notices.title is '공지 제목';
comment on column public.notices.content is '공지 본문 (plain text, 줄바꿈 허용)';
comment on column public.notices.created_at is '작성(공개) 시각';
comment on column public.notices.updated_at is '최종 수정 시각';

-- updated_at 자동 갱신용 공용 함수 (다른 테이블에서도 재사용 가능)
create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger set_notices_updated_at
  before update on public.notices
  for each row execute function public.set_updated_at();

alter table public.notices enable row level security;

-- 조회: 로그인 사용자만 (앱 기능은 로그인 상태에서만 사용 가능)
create policy "Authenticated users can view notices"
  on public.notices for select
  to authenticated
  using (true);

-- 작성/수정/삭제: 관리자(inquiries와 동일한 하드코딩 UID)만 허용
create policy "Admin can insert notices"
  on public.notices for insert
  with check (auth.uid() = '3d6f7e16-c6bd-4a88-afe9-bf9fbbc8c004'::uuid);

create policy "Admin can update notices"
  on public.notices for update
  using (auth.uid() = '3d6f7e16-c6bd-4a88-afe9-bf9fbbc8c004'::uuid);

create policy "Admin can delete notices"
  on public.notices for delete
  using (auth.uid() = '3d6f7e16-c6bd-4a88-afe9-bf9fbbc8c004'::uuid);
