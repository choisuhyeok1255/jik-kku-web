-- inquiries 테이블 생성
create table public.inquiries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  content text not null,
  answer text,
  admin_answer_at timestamptz,
  created_at timestamptz not null default now()
);

comment on table public.inquiries is '문의하기';
comment on column public.inquiries.id is '문의글 id';
comment on column public.inquiries.user_id is '글 작성자 user id';
comment on column public.inquiries.title is '글 제목';
comment on column public.inquiries.content is '문의 내용';
comment on column public.inquiries.answer is '관리자 답변';
comment on column public.inquiries.admin_answer_at is '관리자 답변 시각';
comment on column public.inquiries.created_at is '문의글 생성 시각';

alter table public.inquiries enable row level security;

-- 사용자: 본인 문의만 조회/생성
create policy "Users can view own inquiries"
  on public.inquiries for select
  using (auth.uid() = user_id);

create policy "Users can insert own inquiries"
  on public.inquiries for insert
  with check (auth.uid() = user_id);

-- 관리자(user_id 3d6f7e16-c6bd-4a88-afe9-bf9fbbc8c004): 전체 조회/수정
create policy "Admin can view all inquiries"
  on public.inquiries for select
  using (auth.uid() = '3d6f7e16-c6bd-4a88-afe9-bf9fbbc8c004'::uuid);

create policy "Admin can update inquiries"
  on public.inquiries for update
  using (auth.uid() = '3d6f7e16-c6bd-4a88-afe9-bf9fbbc8c004'::uuid);
